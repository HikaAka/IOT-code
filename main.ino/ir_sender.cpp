//==================================================
// IR送信ピン
//==================================================

const uint16_t IR_SEND_PIN = 4;


//==================================================
// エアコン
//==================================================

IRMitsubishiHeavy152Ac ac(
    IR_SEND_PIN
);


//==================================================
// 汎用IR送信 消す
//==================================================

IRsend irsend(
    IR_SEND_PIN
);


//==================================================
// 初期化
//==================================================

bool ir_sender_init() {

    ac.begin();

    irsend.begin();
    Serial.println("IR Sender OK");

    return true;
}

//==================================================
// 冷房
//==================================================

void sendCool(int temp) {

    ac.on();

    ac.setMode(
        kMitsubishiHeavyCool
    );

    ac.setTemp(temp);

    ac.setFan(
        0
    );

    ac.send();

    Serial.print("COOL ");
    Serial.println(temp);
}


//==================================================
// 暖房
//==================================================

void sendHeat(int temp) {

    ac.on();

    ac.setMode(
        kMitsubishiHeavyHeat
    );

    ac.setTemp(temp);

    ac.setFan(
        0
    );

    ac.send();

    Serial.print("HEAT ");
    Serial.println(temp);
}


//==================================================
// OFF
//==================================================

void sendOff() {

    ac.off();

    ac.send();

    Serial.println("AIRCON OFF");
}






